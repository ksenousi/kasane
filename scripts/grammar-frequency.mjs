// Counts how many Tatoeba sentences contain each N3 grammar pattern (for "sort by most common" on the Grammar tab).
// Each rule tries to match the grammar use and skip common look-alikes.
//
// Usage: download https://downloads.tatoeba.org/exports/per_language/jpn/jpn_sentences.tsv.bz2,
// unpack it, then: node scripts/grammar-frequency.mjs path/to/jpn_sentences.tsv
// Prints the ranking and writes counts.json and samples.json (matched sentences, for spot checks) to the current directory.
import fs from 'node:fs'
const file = process.argv[2]
if (!file) throw new Error('Pass the path to jpn_sentences.tsv')
const dir = process.cwd() + '/'
const sentences = fs.readFileSync(file, 'utf8').split('\n').map((l) => l.split('\t')[2]).filter(Boolean)
const V = '[うくすつぬふむゆるぐずぶぷ]' // dictionary-form endings
const STEM = '[いきしちにひみりぎじびぴえけせてねへめれげぜでべぺ]' // masu-stem endings
const K = '[\\u4e00-\\u9fff]'
const R = (s) => new RegExp(s)
const rules = {
  'おかげで': R('おかげで|お陰で'),
  'せいで': R('せいで|せいだ(?!ろ)'),
  'ために': R('ために|為に'),
  'そのため（に）': R('(?:^|[。、「])そのため'),
  'ことから': R('ことから|事から'),
  'わけだ': R('(?:わけ|訳)(?:だ|です)(?!ろ)'),
  'というのは': R('というのは|と言うのは|っていうのは'),
  'さえ〜ば': R('さえ[^、。]{0,10}?(?:れば|けば|えば|せば|てば|ねば|べば|めば|げば|なら)'),
  'ばいい': R('ばいい|ばよい|ばよかった|ばいかった'),
  'ば〜ほど': R('ば[^、。]{1,6}ほど'),
  'たとえ〜ても': R('(?:たとえ|例え)(?!ば)[^。]*?(?:ても|でも)'),
  'どんなに〜ても': R('どんなに[^。]*?(?:ても|でも)'),
  'にしても': R('にしても'),
  'ながらも': R('ながらも'),
  'くせに': R('くせに|癖に|くせして'),
  'にしては': R('にしては'),
  'ところが': R('(?:^|[。「])ところが'),
  'に違いない': R('に(?:違い|ちがい)(?:ない|ありません|あるまい)'),
  'わけがない': R('(?<!申し)(?:わけ|訳)が(?:ない|ありません)'),
  'とは限らない': R('とは(?:限|かぎ)ら(?:ない|ず)|とは限りません'),
  'もしかしたら': R('もしかしたら|もしかして|もしかすると'),
  'まさか': R('まさか'),
  'ような気がする': R('(?:ような|みたいな)気が'),
  'んだって': R('んだって|んですって'),
  'っけ': R('っけ(?=[？?。！!」]|$|な|ね)'),
  'ということだ': R('(?:ということ|ってこと)(?:だ|です)'),
  'わけではない': R('(?:わけ|訳)(?:では|じゃ|でも)(?:ない|ありません|なかった)'),
  'わけにはいかない': R('わけに(?:は|も)?(?:いか|行か|いき)'),
  'ないことはない': R('ないこと(?:は|も)ない|なくはない|なくもない'),
  'ことはない': R(`(?<=${V})ことは(?:ない|ありません)`),
  'べきではない': R('べき(?:では|じゃ|で)(?:ない|ありません|なかった)'),
  'しかない': R(`(?<=${V})しか(?:ない|ありません|なかった)`),
  'とても〜ない': R('とても[^。、]{0,10}(?:れない|せない|けない|てない|ねない|べない|めない|えない|られない|れません|えません|られません)'),
  '決して〜ない': R('(?:決して|けっして)[^。]{0,20}(?:ない|ません|なかった|ぬ|な[。！!])'),
  'めったに〜ない': R('めったに|滅多に'),
  '別に〜ない': R('別に[^。、]{0,10}(?:ない|ません|なかった)'),
  'ほど〜ない': R('ほど[^。、]{1,10}(?:ない|ません|なかった)'),
  'なかなか': R('なかなか|中々'),
  'ずに': R('ずに(?!は)'),
  'ずにはいられない': R('ずにはいられ|ずにはおれ'),
  'ようとしない': R('[よう]うとし(?:ない|なかった|ません)|ようとしない'),
  'どうしても': R('どうしても'),
  'うちに': R('(?<=[るいなのたでて])うちに'),
  '最中に': R('最中|さいちゅう'),
  'たびに': R('たびに|(?<![一二三何])度に'),
  'につれて': R('につれ'),
  '一方だ': R('(?<=[るい])一方(?:だ|です|で)'),
  'たて': R('(?<=[きしちにひみりいえけせてねへめれぎじびぴ])たて(?:の|だ|で|です)'),
  'きり': R('(?:たきり|だきり|人きり|れきり)'),
  '中': R(`(?<=${K}{2})中(?=[はにだのでもを、。]|です)`),
  '上で': R('(?<=[たるうくすの])(?:上で|うえで)(?=[、はもの])|(?<=[たる])上で'),
  'すでに': R('すでに|既に'),
  'と共に': R('と共に|とともに'),
  'あまり': R('あまりに|あまりの|のあまり'),
  'ほど': R('(?<!なる)(?<=[いる])ほど(?![^。、]{0,10}(?:ない|ません))(?<!ば[^、。]{0,6}ほど)'),
  'こそ': R('(?<!こそ)こそ(?!こそ|あど)'),
  'さえ': R('(?<!さ)さえ(?![ぎずる])(?![^、。]{0,10}?(?:れば|けば|えば|せば|てば|ねば|べば|めば|げば))'),
  'に比べて': R('に(?:比べ|くらべ|比較し)'),
  'むしろ': R('むしろ|寧ろ'),
  'というより': R('(?:という|っていう|と言う)より'),
  'はもちろん': R('は(?:もちろん|勿論)'),
  'ばかりでなく': R('ばかり(?:で|では)なく|ばかりか'),
  'をはじめ': R('を(?:はじめ|始め|初め)(?![るたまてよらなろ])'),
  '一体': R('一体|いったい'),
  'わざわざ': R('わざわざ'),
  'つい': R('(?<![にお])つい(?![てにでたさ])(?=[^。]{0,15}(?:しま|ちゃ|ちま))|ついつい'),
  'について': R('について|につき|に就いて|についての'),
  'に対して': R('に対し|に対する'),
  'として': R('(?<![うおさ])として'),
  'にかけて': R('から[^。]{1,12}にかけて'),
  'は〜で有名': R('で有名|でゆうめい'),
  '向き': R('(?<![前後上下横外内表裏])向き(?:だ|の|に|で|な|です)'),
  '向け': R('向け(?:の|に|だ|です)'),
  'つまり': R('つまり|詰まり'),
  'さて': R('(?:^|[。「])さて'),
  'ところで': R('(?:^|[。「])ところで'),
  'がたい': R(`(?<!あり)(?<=${STEM})がた(?:い|く)`),
  'がち': R(`(?<=${K}|${STEM})がち(?:だ|な|で|の|に|です)`),
  'っぽい': R('っぽ(?:い|く|さ)'),
  'だらけ': R('だらけ'),
  'っぱなし': R('っぱなし|っ放し'),
  '的': R('(?<![目標射])(?<=[\\u4e00-\\u9fff])的(?:な|に|で|だ|です|には)'),
  '切る': R(`(?<!締め)(?<=${STEM})(?<!に)切(?:る|った|って|り(?!替)|ら|れ(?!な))`),
  '切れない': R(`(?<=${STEM})(?:切れ|きれ)(?:ない|ません|なかった)`),
  '合う': R(`(?<!知り|付き|つき|落ち|似|見)(?<=${STEM})(?<!に)合(?:う|っ|い(?!言)|わ|え|お)`),
  'ずつ': R('ずつ|づつ'),
  'ついでに': R('ついでに|ついで'),
  '代わりに': R('代わりに|代りに|かわりに'),
  'ふりをする': R('(?:ふり|振り)を?し'),
  'たものだ': R('[ただ](?:ものだ|ものです|もんだ)(?!から)'),
  'てごらん': R('[てで](?:ごらん|御覧)'),
}
const counts = {}, samples = {}
for (const [k, re] of Object.entries(rules)) { counts[k] = 0; samples[k] = [] }
for (const s of sentences) {
  for (const [k, re] of Object.entries(rules)) {
    if (re.test(s)) {
      counts[k]++
      if (samples[k].length < 400) samples[k].push(s)
    }
  }
}
const total = sentences.length
const ranked = Object.entries(counts).sort((a, b) => b[1] - a[1])
fs.writeFileSync(dir + 'counts.json', JSON.stringify({ total, counts }, null, 1))
fs.writeFileSync(dir + 'samples.json', JSON.stringify(samples))
console.log('sentences', total, 'rules', Object.keys(rules).length)
for (const [k, n] of ranked) console.log(String(n).padStart(6), (n / total * 1e4).toFixed(1).padStart(7), k)
